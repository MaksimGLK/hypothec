function Section({ id, title, children }: { id: string; title: string; children: ReactNode }) {
  return (
    <section id={id} className="mt-10 scroll-mt-6">
      <h2 className="mb-3 text-xl font-semibold">{title}</h2>
      <div className="space-y-3 text-[15px]">{children}</div>
    </section>
  );
}

function Steps({ items }: { items: { title: string; where: ReactNode; text: string }[] }) {
  return (
    <ol className="space-y-3">
      {items.map((s, i) => (
        <li key={s.title} className="flex gap-3 rounded-2xl border border-border bg-surface p-4">
          <span className="flex size-7 shrink-0 items-center justify-center rounded-full bg-primary-soft text-sm font-semibold text-primary">{i + 1}</span>
          <div>
            <p className="font-medium">
              {s.title} <span className="text-sm font-normal text-ink-2">— {s.where}</span>
            </p>
            <p className="mt-1 text-sm text-ink-2">{s.text}</p>
          </div>
        </li>
      ))}
    </ol>
  );
}

function Table({ head, rows }: { head: string[]; rows: ReactNode[][] }) {
  return (
    <div className="-mx-4 overflow-x-auto sm:mx-0">
      <table className="w-full min-w-[480px] overflow-hidden text-left text-sm sm:rounded-2xl sm:border sm:border-border">
        <thead className="bg-surface-2">
          <tr>
            {head.map((h) => (
              <th key={h} className="px-4 py-2 font-medium">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className="bg-surface">
          {rows.map((r, i) => (
            <tr key={i} className="border-t border-border align-top">
              {r.map((c, j) => (
                <td key={j} className="px-4 py-2.5">
                  {c}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function Faq({ q, children }: { q: string; children: ReactNode }) {
  return (
    <details className="rounded-2xl border border-border bg-surface px-4 py-3">
      <summary className="cursor-pointer font-medium">{q}</summary>
      <p className="mt-2 text-sm text-ink-2">{children}</p>
    </details>
  );
}
